"""gpufleet CLI. `python3 -m gpufleet <cmd>` (or the `./gpufleet` shim).

Commands:
  pregate                     local no-GPU battery (required before spend)
  offers [--gpu 4090 ...]     price/stock per GPU type
  status                      pods + $/hr + gpu util + idle warnings
  up --gpu 4090 [...]         create (budget-guarded) + wait + bootstrap(+deadman)
  bootstrap --pod ID          re-run bootstrap/deadman on an existing pod
  push --pod ID               build_and_push.sh to one pod
  run MANIFEST [--pod ID|--auto ...]   the whole session; stops pod at the end
  ssh --pod ID [CMD]          interactive/one-shot ssh
  stop|resume|terminate --pod ID|--all
  ledger                      spend report
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

from . import (
    DEFAULT_DISK_GB,
    DEFAULT_IDLE_STOP_MIN,
    DEFAULT_IMAGE,
    DEFAULT_MAX_USD_HR,
    DEFAULT_TTL_HOURS,
    DEFAULT_VOLUME_GB,
    GPU_TYPE_IDS,
    VOLUME_MOUNT,
)
from . import api, ledger, pregate
from .manifest import ManifestRun
from .podctl import Endpoint, bootstrap, health_check, ssh_run, wait_ready

FLEET_DIR = Path(__file__).resolve().parent.parent
GPU_BENCH = FLEET_DIR.parent  # gpu_benchmarks/
STWO_CAIRO = GPU_BENCH.parent
STWO = STWO_CAIRO.parent / "stwo"
RESULTS = GPU_BENCH / "results"
REPOS = {"stwo": STWO, "stwo-cairo": STWO_CAIRO}


def _gpu_type(short: str) -> str:
    return GPU_TYPE_IDS.get(short.lower(), short)


def cmd_pregate(_args) -> int:
    return 0 if pregate.run(STWO, STWO_CAIRO) else 1


def cmd_offers(args) -> int:
    ids = [_gpu_type(g) for g in (args.gpu or list(GPU_TYPE_IDS))]
    rows = api.gpu_offers(ids)
    print(f"{'gpu':<28} {'vram':>5} {'od $/hr':>8} {'spot':>7} {'stock':<8} clouds")
    for r in sorted(rows, key=lambda r: (r["od_usd_hr"] is None, r["od_usd_hr"] or 9e9)):
        clouds = "/".join(c for c, on in (("sec", r["secure"]), ("com", r["community"])) if on)
        od = f"{r['od_usd_hr']:.2f}" if r["od_usd_hr"] else "-"
        spot = f"{r['spot_usd_hr']:.2f}" if r["spot_usd_hr"] else "-"
        print(f"{r['name']:<28} {r['vram_gb'] or '?':>5} {od:>8} {spot:>7} "
              f"{(r['stock'] or '?'):<8} {clouds}")
    return 0


def cmd_status(_args) -> int:
    pods = api.list_pods()
    if not pods:
        print("no pods")
        return 0
    print(f"{'id':<16} {'name':<22} {'gpu':<24} {'status':<10} {'$/hr':>6} "
          f"{'up_h':>6} {'util%':>5} ssh")
    for p in pods:
        up_h = p.uptime_s / 3600
        util = "-" if p.gpu_util is None else str(p.gpu_util)
        ssh = f"{p.ssh_host}:{p.ssh_port}" if p.ssh_host else "-"
        warn = ""
        if p.status == "RUNNING" and (p.gpu_util or 0) < 5 and p.uptime_s > 1800:
            warn = "  <- RUNNING+IDLE (billing!)"
        print(f"{p.id:<16} {p.name[:22]:<22} {p.gpu[:24]:<24} {p.status:<10} "
              f"{p.cost_per_hr:>6.2f} {up_h:>6.1f} {util:>5} {ssh}{warn}")
    return 0


def _sync_pods_conf() -> None:
    """Regenerate fleet/pods.conf from the live roster so build_and_push.sh and
    the loop scripts keep working unchanged (first RUNNING pod = builder)."""
    running = [p for p in api.list_pods() if p.status == "RUNNING" and p.ssh_host]
    lines = [
        "# GENERATED by gpufleet (status sync) — ID|HOST|PORT|GPU|VRAM_GB|VCPU|USD_HR|NOTES",
        "# First line is the build_and_push.sh builder. Edit order to change it.",
    ]
    running.sort(key=lambda p: -p.vcpu)  # most cores first = best builder
    for p in running:
        lines.append(
            f"{p.id}|{p.ssh_host}|{p.ssh_port}|{p.gpu.replace(' ', '_')}|?|"
            f"{p.vcpu}|{p.cost_per_hr:.2f}|gpufleet"
        )
    (FLEET_DIR / "pods.conf").write_text("\n".join(lines) + "\n")


def do_up(args) -> api.PodInfo | None:
    gpu_type = _gpu_type(args.gpu)
    offers = api.gpu_offers([gpu_type])
    price = next((o["od_usd_hr"] for o in offers if o["od_usd_hr"]), None)
    if price is None:
        print(f"no on-demand price for {gpu_type} (no stock?)")
        return None
    if price > args.max_usd_hr and not args.force:
        print(f"REFUSED: {gpu_type} at ${price:.2f}/hr exceeds ceiling "
              f"${args.max_usd_hr:.2f}/hr (--max-usd-hr or --force to override)")
        return None
    print(f"[gpufleet] creating {gpu_type} (~${price:.2f}/hr, ttl {args.ttl_hours}h, "
          f"idle-stop {args.idle_min}min)")
    pod = api.create_pod(
        name=args.name or f"stwo-{args.gpu}",
        gpu_type_id=gpu_type,
        image=args.image,
        cloud=args.cloud,
        disk_gb=args.disk_gb,
        volume_gb=args.volume_gb,
        volume_mount=VOLUME_MOUNT,
        min_vcpu=args.min_vcpu,
        min_mem_gb=args.min_mem_gb,
        network_volume_id=args.volume_id,
    )
    ledger.append("create", pod_id=pod.id, gpu=pod.gpu, usd_hr=pod.cost_per_hr or price,
                  purpose=args.purpose)
    print(f"[gpufleet] pod {pod.id} created; waiting for ssh ...")
    pod = wait_ready(pod.id, timeout_s=args.ready_timeout)
    ep = Endpoint.of(pod)
    print(f"[gpufleet] ssh ready at {ep.host}:{ep.port}; bootstrapping ...")
    if not bootstrap(ep, ttl_hours=args.ttl_hours, idle_min=args.idle_min,
                     log_file=RESULTS / "bootstrap" / f"{pod.id}.log"):
        print("bootstrap FAILED (pod left running for inspection)")
        return None
    for k, v in health_check(ep).items():
        print(f"  {k}: {v}")
    _sync_pods_conf()
    print(f"[gpufleet] up: {pod.id}  ({ep.host}:{ep.port})")
    return pod


def cmd_up(args) -> int:
    return 0 if do_up(args) else 1


def _resolve_pod(pod_id: str) -> tuple[api.PodInfo, Endpoint]:
    pod = api.get_pod(pod_id)
    if not pod:
        raise SystemExit(f"no such pod: {pod_id}")
    return pod, Endpoint.of(pod)


def cmd_bootstrap(args) -> int:
    pod, ep = _resolve_pod(args.pod)
    ok = bootstrap(ep, ttl_hours=args.ttl_hours, idle_min=args.idle_min,
                   log_file=RESULTS / "bootstrap" / f"{pod.id}.log")
    print("bootstrap " + ("ok" if ok else "FAILED"))
    return 0 if ok else 1


def cmd_push(args) -> int:
    pod, _ep = _resolve_pod(args.pod)
    # build_and_push.sh drives itself from pods.conf (first line = builder unless
    # --builder): refresh the roster from the live API, then delegate.
    _sync_pods_conf()
    script = FLEET_DIR / "build_and_push.sh"
    return subprocess.run(
        ["bash", str(script), "--builder", pod.id], cwd=FLEET_DIR, check=False
    ).returncode


def cmd_run(args) -> int:
    if not args.skip_pregate and not pregate.is_fresh(STWO, STWO_CAIRO):
        print("[gpufleet] pregate not green/fresh — running it first "
              "(--skip-pregate to override)")
        if not pregate.run(STWO, STWO_CAIRO):
            print("[gpufleet] REFUSING to spend: local battery failed")
            return 1

    if args.pod:
        pod, ep = _resolve_pod(args.pod)
        if pod.status != "RUNNING":
            print(f"[gpufleet] resuming {pod.id} ...")
            api.resume_pod(pod.id)
            ledger.append("resume", pod_id=pod.id, gpu=pod.gpu, usd_hr=pod.cost_per_hr,
                          purpose=args.purpose)
            pod = wait_ready(pod.id)
            ep = Endpoint.of(pod)
        _sync_pods_conf()
    elif args.auto:
        up_args = argparse.Namespace(
            gpu=args.auto, name=None, image=DEFAULT_IMAGE, cloud="SECURE",
            disk_gb=DEFAULT_DISK_GB, volume_gb=DEFAULT_VOLUME_GB, volume_id=None,
            min_vcpu=16, min_mem_gb=62, max_usd_hr=args.max_usd_hr, force=False,
            ttl_hours=args.ttl_hours, idle_min=DEFAULT_IDLE_STOP_MIN,
            ready_timeout=600, purpose=args.purpose,
        )
        pod = do_up(up_args)
        if not pod:
            return 1
        ep = Endpoint.of(pod)
    else:
        print("need --pod ID or --auto GPU")
        return 1

    if args.push:
        push_args = argparse.Namespace(pod=pod.id)
        if cmd_push(push_args) != 0:
            print("[gpufleet] push failed; leaving pod as-is")
            return 1

    run = ManifestRun(Path(args.manifest), RESULTS, REPOS)
    summary = run.execute(ep, {"id": pod.id, "gpu": pod.gpu, "usd_hr": pod.cost_per_hr})
    ledger.append("run", pod_id=pod.id, gpu=pod.gpu, usd_hr=pod.cost_per_hr,
                  purpose=args.purpose, run_id=summary["run_id"],
                  note=("PASS" if summary["passed"] else "FAIL"))

    # Lifecycle policy: stop by default (GPU billing ends, disk kept for a warm
    # resume); --terminate to release the disk too; --keep only when another run
    # is imminent — a kept pod is the ONLY state that bills while idle.
    if args.keep:
        print(f"[gpufleet] --keep: pod {pod.id} left RUNNING (billing!)")
    elif args.terminate:
        api.terminate_pod(pod.id)
        ledger.append("terminate", pod_id=pod.id, gpu=pod.gpu)
        print(f"[gpufleet] pod {pod.id} terminated")
    else:
        api.stop_pod(pod.id)
        ledger.append("stop", pod_id=pod.id, gpu=pod.gpu)
        print(f"[gpufleet] pod {pod.id} stopped (disk kept; `resume` to reuse)")

    print(f"[gpufleet] {'PASS' if summary['passed'] else 'FAIL'} — "
          f"results in {run.dir}")
    return 0 if summary["passed"] else 1


def cmd_ssh(args) -> int:
    from .podctl import SSH_OPTS

    _, ep = _resolve_pod(args.pod)
    if args.remote_cmd:
        return ssh_run(ep, " ".join(args.remote_cmd))
    import os

    os.execvp("ssh", ["ssh", *SSH_OPTS, "-p", str(ep.port), f"root@{ep.host}"])


def cmd_check_manifest(args) -> int:
    """Validate a manifest offline: TOML parse, step shape, criterion ops."""
    try:
        run = ManifestRun(Path(args.manifest), RESULTS, REPOS)
    except Exception as e:
        print(f"INVALID: {e}")
        return 1
    steps = run.spec.get("step", [])
    ok = True
    if not steps:
        print("INVALID: no [[step]] entries")
        ok = False
    for s in steps:
        for key in ("name", "cmd"):
            if key not in s:
                print(f"INVALID: step missing {key!r}: {s}")
                ok = False
        for a in s.get("assert", []):
            if a.get("op", "eq") not in ("eq", "ne", "ge", "le", "exists", "contains"):
                print(f"INVALID: bad assert op in step {s.get('name')}: {a}")
                ok = False
    # The freshly-minted run dir is empty on a check — remove it.
    try:
        (run.dir / "summary.json").unlink(missing_ok=True)
        run.dir.rmdir()
    except OSError:
        pass
    if ok:
        print(f"OK: {run.name} ({len(steps)} steps)")
    return 0 if ok else 1


def _lifecycle(args, action: str) -> int:
    targets = []
    if args.all:
        targets = [p for p in api.list_pods()
                   if action != "stop" or p.status == "RUNNING"]
    elif args.pod:
        pod = api.get_pod(args.pod)
        targets = [pod] if pod else []
    if not targets:
        print("nothing to do")
        return 0
    for p in targets:
        if action == "stop":
            api.stop_pod(p.id)
        elif action == "resume":
            api.resume_pod(p.id)
        else:
            api.terminate_pod(p.id)
        ledger.append(action, pod_id=p.id, gpu=p.gpu, usd_hr=p.cost_per_hr)
        print(f"{action}: {p.id} ({p.gpu})")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(prog="gpufleet")
    sub = ap.add_subparsers(dest="cmd", required=True)

    sub.add_parser("pregate")
    p = sub.add_parser("offers")
    p.add_argument("--gpu", nargs="*")
    sub.add_parser("status")
    sub.add_parser("ledger")

    p = sub.add_parser("up")
    p.add_argument("--gpu", required=True)
    p.add_argument("--name")
    p.add_argument("--image", default=DEFAULT_IMAGE)
    p.add_argument("--cloud", default="SECURE", choices=["SECURE", "COMMUNITY"])
    p.add_argument("--disk-gb", type=int, default=DEFAULT_DISK_GB)
    p.add_argument("--volume-gb", type=int, default=DEFAULT_VOLUME_GB)
    p.add_argument("--volume-id", help="network volume id (warm target dir)")
    p.add_argument("--min-vcpu", type=int, default=16)
    p.add_argument("--min-mem-gb", type=int, default=62)
    p.add_argument("--max-usd-hr", type=float, default=DEFAULT_MAX_USD_HR)
    p.add_argument("--force", action="store_true")
    p.add_argument("--ttl-hours", type=float, default=DEFAULT_TTL_HOURS)
    p.add_argument("--idle-min", type=int, default=DEFAULT_IDLE_STOP_MIN)
    p.add_argument("--ready-timeout", type=float, default=600)
    p.add_argument("--purpose", default="")

    p = sub.add_parser("bootstrap")
    p.add_argument("--pod", required=True)
    p.add_argument("--ttl-hours", type=float, default=DEFAULT_TTL_HOURS)
    p.add_argument("--idle-min", type=int, default=DEFAULT_IDLE_STOP_MIN)

    p = sub.add_parser("push")
    p.add_argument("--pod", required=True)

    p = sub.add_parser("run")
    p.add_argument("manifest")
    p.add_argument("--pod")
    p.add_argument("--auto", metavar="GPU", help="provision this GPU type for the run")
    p.add_argument("--push", action="store_true", help="build_and_push.sh first")
    p.add_argument("--keep", action="store_true", help="leave pod running after")
    p.add_argument("--terminate", action="store_true", help="terminate (not stop) after")
    p.add_argument("--skip-pregate", action="store_true")
    p.add_argument("--max-usd-hr", type=float, default=DEFAULT_MAX_USD_HR)
    p.add_argument("--ttl-hours", type=float, default=DEFAULT_TTL_HOURS)
    p.add_argument("--purpose", default="")

    p = sub.add_parser("ssh")
    p.add_argument("--pod", required=True)
    p.add_argument("remote_cmd", nargs="*")

    p = sub.add_parser("check-manifest")
    p.add_argument("manifest")

    for name in ("stop", "resume", "terminate"):
        p = sub.add_parser(name)
        p.add_argument("--pod")
        p.add_argument("--all", action="store_true")

    args = ap.parse_args()
    return {
        "pregate": cmd_pregate,
        "offers": cmd_offers,
        "status": cmd_status,
        "ledger": lambda _a: (print(ledger.report()), 0)[1],
        "up": cmd_up,
        "bootstrap": cmd_bootstrap,
        "push": cmd_push,
        "run": cmd_run,
        "ssh": cmd_ssh,
        "check-manifest": cmd_check_manifest,
        "stop": lambda a: _lifecycle(a, "stop"),
        "resume": lambda a: _lifecycle(a, "resume"),
        "terminate": lambda a: _lifecycle(a, "terminate"),
    }[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
