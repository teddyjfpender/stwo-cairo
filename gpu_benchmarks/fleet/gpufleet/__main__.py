POD_ID_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._:-]{0,127}")
LEASE_NAME_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9-]{0,63}")
CREATE_RECONCILE_DISCOVERY_S = 60.0
CREATE_RECONCILE_TIMEOUT_S = 90.0
CREATE_RECONCILE_POLL_S = 2.0


def _gpu_type(short: str) -> str:
    return GPU_TYPE_IDS.get(short.lower(), short)


def cmd_pregate(_args) -> int:
    return 0 if pregate.run(STWO, STWO_CAIRO) else 1


def cmd_require_pregate(_args) -> int:
    if pregate.is_fresh(STWO, STWO_CAIRO):
        print("[gpufleet] fresh source-bound pregate confirmed")
        return 0
    print("[gpufleet] REFUSING to spend: pregate is stale or not green")
    return 1


def cmd_source_hash(args) -> int:
    print(projection_identity(Path(args.repo))["worktree_sha256"])
    return 0


def cmd_lease_policy(args) -> int:
    for line in load_lease_policy(Path(args.recipe)).env_lines():
        print(line)
    return 0


def cmd_offers(args) -> int:
    ids = [_gpu_type(g) for g in (args.gpu or list(GPU_TYPE_IDS))]
    rows = api.gpu_offers(ids)
    print(f"{'gpu':<28} {'vram':>5} {'od $/hr':>8} {'spot':>7} {'stock':<8} clouds")
    for r in sorted(rows, key=lambda r: (r["od_usd_hr"] is None, r["od_usd_hr"] or 9e9)):
        clouds = "/".join(c for c, on in (("sec", r["secure"]), ("com", r["community"])) if on)
        od = f"{r['od_usd_hr']:.2f}" if r["od_usd_hr"] else "-"
        spot = f"{r['spot_usd_hr']:.2f}" if r["spot_usd_hr"] else "-"
        print(f"{r['name']:<28} {r['vram_gb'] or '?':>5} {od:>8} {spot:>7} "
              f"{(r['stock'] or '?'):<8} {clouds}")
    return 0


def cmd_status(_args) -> int:
    pods = api.list_pods()
    if not pods:
        print("no pods")
        return 0
    print(f"{'id':<16} {'name':<22} {'gpu':<24} {'status':<10} {'$/hr':>6} "
          f"{'up_h':>6} {'util%':>5} ssh")
    for p in pods:
        up_h = p.uptime_s / 3600
        util = "-" if p.gpu_util is None else str(p.gpu_util)
        ssh = f"{p.ssh_host}:{p.ssh_port}" if p.ssh_host else "-"
        warn = ""
        if p.status == "RUNNING" and (p.gpu_util or 0) < 5 and p.uptime_s > 1800:
            warn = "  <- RUNNING+IDLE (billing!)"
        print(f"{p.id:<16} {p.name[:22]:<22} {p.gpu[:24]:<24} {p.status:<10} "
              f"{p.cost_per_hr:>6.2f} {up_h:>6.1f} {util:>5} {ssh}{warn}")
    return 0


def _sync_pods_conf() -> None:
    """Regenerate fleet/pods.conf from the live roster so build_and_push.sh and
    the loop scripts keep working unchanged (first RUNNING pod = builder)."""
    running = [p for p in api.list_pods() if p.status == "RUNNING" and p.ssh_host]
    lines = [
        "# GENERATED by gpufleet (status sync) — ID|HOST|PORT|GPU|VRAM_GB|VCPU|USD_HR|NOTES",
        "# First line is the build_and_push.sh builder. Edit order to change it.",
    ]
    running.sort(key=lambda p: -p.vcpu)  # most cores first = best builder
    for p in running:
        lines.append(
            f"{p.id}|{p.ssh_host}|{p.ssh_port}|{p.gpu.replace(' ', '_')}|?|"
            f"{p.vcpu}|{p.cost_per_hr:.2f}|gpufleet"
        )
    (FLEET_DIR / "pods.conf").write_text("\n".join(lines) + "\n")


def _require_pregate() -> bool:
    if pregate.is_fresh(STWO, STWO_CAIRO):
        return True
    print("[gpufleet] pregate not green/fresh — running it before spend")
    if pregate.run(STWO, STWO_CAIRO):
        return True
    print("[gpufleet] REFUSING to spend: local battery failed")
    return False


def _resume_matches_policy(args, policy: LeasePolicy) -> bool:
    return (
        _gpu_type(args.gpu) == _gpu_type(policy.gpu)
        and args.name_prefix == policy.name_prefix
        and args.max_usd_hr == policy.max_usd_hr
        and args.min_vcpu == policy.min_vcpu
        and args.min_mem_gb == policy.min_mem_gb
        and args.ttl_hours == policy.ttl_hours
        and args.idle_min == policy.idle_min
        and args.one_shot == policy.one_shot
        and args.failure_action == policy.final_action
    )


def _require_provider_admission(
    args, provision_policy: LeasePolicy | None = None
) -> dict[str, object] | None:
    recipe_value = getattr(args, "recipe", None)
    recipe = Path(recipe_value) if recipe_value else None
    if recipe is not None and pregate.is_sn2_5mhz_cheap_recipe(recipe, STWO_CAIRO):
        policy = provision_policy or load_lease_policy(recipe)
        if policy != pregate.SN2_5MHZ_CHEAP_POLICY or (
            provision_policy is None and not _resume_matches_policy(args, policy)
        ):
            raise ValueError(
                "SN2 5 MHz cheap-GPU operation differs from its exact A40 lease"
            )
        return pregate.admit_sn2_5mhz_cheap(recipe, STWO, STWO_CAIRO)

    if recipe is None or not pregate.is_sn2_vertical_recipe(recipe, STWO_CAIRO):
        return {"scope": "formal-pregate"} if _require_pregate() else None

    policy = load_lease_policy(recipe)
    if (
        policy.one_shot
        or policy.final_action != "stop"
        or policy.gpu != "h100"
        or policy.gpu_count != 1
        or policy.min_vcpu < 16
        or policy.min_mem_gb < 62
        or policy.ttl_hours > 2
        or policy.idle_min > 15
        or policy.max_usd_hr > 3
        or policy.name_prefix != "replacement-v1-sn2-"
        or (
            provision_policy is not None
            and provision_policy != policy
        )
        or (
            provision_policy is None
            and not _resume_matches_policy(args, policy)
        )
    ):
        raise ValueError("SN2 vertical resume differs from its bounded H100 lease")
    return pregate.admit_sn2_vertical(recipe, STWO, STWO_CAIRO)


def _require_resume_admission(args) -> dict[str, object] | None:
    return _require_provider_admission(args)


def _provider_admission_is_current(
    receipt: dict[str, object], recipe_value: str | None
) -> bool:
    if receipt.get("scope") == pregate.SN2_5MHZ_CHEAP_SCOPE:
        return bool(recipe_value) and pregate.sn2_5mhz_cheap_is_current(
            receipt, Path(recipe_value), STWO, STWO_CAIRO
        )
    if receipt.get("scope") == pregate.SN2_VERTICAL_SCOPE:
        return bool(recipe_value) and pregate.sn2_vertical_is_current(
            receipt, Path(recipe_value), STWO, STWO_CAIRO
        )
    return receipt.get("scope") == "formal-pregate" and pregate.is_fresh(
        STWO, STWO_CAIRO
    )


def _resume_admission_is_current(
    receipt: dict[str, object], recipe_value: str | None
) -> bool:
    return _provider_admission_is_current(receipt, recipe_value)


def _bind_explicit_ssh_key() -> None:
    pod_control._ssh_opts()


def _install_deadman_first(
    ep: Endpoint,
    *,
    ttl_hours: float,
    idle_min: int,
    log_file: Path,
) -> None:
    if ssh_run(
        ep,
        deadman_script(ttl_hours, idle_min),
        timeout=60,
        log_file=log_file,
    ):
        raise RuntimeError("deadman installation failed")
    if ssh_run(
        ep,
        "test -s /var/run/gpufleet-deadman.pid && "
        "kill -0 \"$(cat /var/run/gpufleet-deadman.pid)\"",
        timeout=20,
        log_file=log_file,
    ):
        raise RuntimeError("deadman liveness check failed")


def _lease_name(args) -> str:
    if args.name:
        name = args.name
    else:
        gpu = re.sub(r"[^a-z0-9]+", "-", args.gpu.lower()).strip("-") or "gpu"
        name = f"stwo-{gpu[:32]}-{secrets.token_hex(4)}"
    if not LEASE_NAME_RE.fullmatch(name):
        raise ValueError("pod name must be 1-64 letters, digits, or hyphens")
    return name


def _apply_recipe_lease(args) -> LeasePolicy:
    if not getattr(args, "recipe", None):
        raise ValueError("--recipe is required for every provisioning operation")
    policy = load_lease_policy(Path(args.recipe))
    if args.gpu and _gpu_type(args.gpu) != _gpu_type(policy.gpu):
        raise ValueError("--gpu conflicts with the recipe lease policy")
    args.gpu = policy.gpu
    args.min_vcpu = policy.min_vcpu
    args.min_mem_gb = policy.min_mem_gb
    args.max_usd_hr = policy.max_usd_hr
    args.ttl_hours = policy.ttl_hours
    args.idle_min = policy.idle_min
    if args.name is None:
        args.name = f"{policy.name_prefix}{secrets.token_hex(4)}"
    if not args.name.startswith(policy.name_prefix):
        raise ValueError("--name does not match the recipe lease prefix")
    if policy.one_shot and args.volume_id:
        raise ValueError("one-shot leases cannot attach a persistent network volume")
    return policy


def _validate_pod_admission(
    pod: api.PodInfo,
    *,
    expected_gpu: str,
    max_usd_hr: float,
    min_vcpu: int,
    min_mem_gb: int,
    exact_name: str | None = None,
    name_prefix: str | None = None,
) -> None:
    if not POD_ID_RE.fullmatch(pod.id):
        raise RuntimeError(f"pod returned an unsafe id: {pod.id!r}")
    if exact_name is not None and pod.name != exact_name:
        raise RuntimeError(f"pod name mismatch: {pod.name!r} != {exact_name!r}")
    if name_prefix is not None and not pod.name.startswith(name_prefix):
        raise RuntimeError(
            f"pod name {pod.name!r} does not start with {name_prefix!r}"
        )
    if pod.gpu != expected_gpu:
        raise RuntimeError(f"pod GPU mismatch: {pod.gpu!r} != {expected_gpu!r}")
    gpu_count = pod.raw.get("gpuCount")
    if isinstance(gpu_count, bool) or gpu_count != 1:
        raise RuntimeError(f"pod GPU count mismatch: {gpu_count!r}")
    if pod.vcpu < min_vcpu or pod.mem_gb < min_mem_gb:
        raise RuntimeError(
            "pod resource floor mismatch: "
            f"vcpu={pod.vcpu}/{min_vcpu}, memory_gb={pod.mem_gb}/{min_mem_gb}"
        )
    if (
        not math.isfinite(max_usd_hr)
        or max_usd_hr <= 0
        or not math.isfinite(pod.cost_per_hr)
        or pod.cost_per_hr <= 0
        or pod.cost_per_hr > max_usd_hr
    ):
        raise RuntimeError(
            f"pod rate ${pod.cost_per_hr}/hr exceeds or invalidates "
            f"the ${max_usd_hr:.2f}/hr ceiling"
        )


def _validate_created_pod(pod: api.PodInfo, name: str, offer: dict, args) -> None:
    _validate_pod_admission(
        pod,
        expected_gpu=offer["display_name"],
        max_usd_hr=args.max_usd_hr,
        min_vcpu=args.min_vcpu,
        min_mem_gb=args.min_mem_gb,
        exact_name=name,
    )


def _require_unique_account_pod(name: str, pod_id: str) -> None:
    matches = [pod for pod in api.list_pods() if pod.name == name]
    if len(matches) != 1 or matches[0].id != pod_id:
        ids = ",".join(pod.id for pod in matches) or "none"
        raise RuntimeError(f"lease name {name!r} resolved to unexpected pods: {ids}")


def _prepare_existing_pod(args) -> tuple[api.PodInfo, Endpoint]:
    """Admit, resume/adopt, and guard one exact existing pod before work."""
    if not args.gpu or not args.name_prefix:
        raise ValueError("existing-pod admission requires --gpu and --name-prefix")
    if not LEASE_NAME_RE.fullmatch(args.name_prefix.rstrip("-")):
        raise ValueError("--name-prefix must be a safe nonempty lease prefix")
    if (
        not math.isfinite(args.ttl_hours)
        or args.ttl_hours <= 0
        or args.idle_min <= 0
        or not math.isfinite(args.ready_timeout)
        or args.ready_timeout <= 0
        or args.min_vcpu <= 0
        or args.min_mem_gb <= 0
        or not math.isfinite(args.max_usd_hr)
        or args.max_usd_hr <= 0
    ):
        raise ValueError("pod admission limits must be finite and positive")
    _bind_explicit_ssh_key()
    admission = _require_resume_admission(args)
    if admission is None:
        raise RuntimeError("fresh pregate required before pod resume or adoption")
    gpu_type = _gpu_type(args.gpu)
    offer = api.secure_offer(gpu_type)
    if offer["usd_hr"] > args.max_usd_hr:
        raise RuntimeError(
            f"current Secure price ${offer['usd_hr']:.2f}/hr exceeds "
            f"the ${args.max_usd_hr:.2f}/hr ceiling"
        )
    pod = api.get_pod(args.pod)
    if pod is None:
        raise RuntimeError(f"no such pod: {args.pod}")
    if pod.id != args.pod:
        raise RuntimeError(f"pod lookup returned {pod.id!r} for {args.pod!r}")
    _validate_pod_admission(
        pod,
        expected_gpu=offer["display_name"],
        max_usd_hr=args.max_usd_hr,
        min_vcpu=args.min_vcpu,
        min_mem_gb=args.min_mem_gb,
        name_prefix=args.name_prefix,
    )
    if (
        admission.get("scope") == pregate.SN2_5MHZ_CHEAP_SCOPE
        and re.fullmatch(re.escape(args.name_prefix) + r"[0-9a-f]{8}", pod.name)
        is None
    ):
        raise RuntimeError("SN2 5 MHz one-shot pod name is not an exact lease name")
    if pod.status not in {"EXITED", "RUNNING"}:
        raise RuntimeError(f"pod {pod.id} is not resumable: {pod.status}")
    if args.one_shot and pod.status != "RUNNING":
        raise RuntimeError("one-shot leases cannot reuse an exited pod")
    if args.one_shot and args.failure_action != "terminate":
        raise ValueError("one-shot admission requires --failure-action terminate")

    admitted_pod = pod
    billing_possible = True
    try:
        if admitted_pod.status == "EXITED":
            print(f"[gpufleet] resuming admitted pod {admitted_pod.id} ...")
            api.resume_pod(admitted_pod.id)
            ledger.append(
                "resume",
                pod_id=admitted_pod.id,
                gpu=admitted_pod.gpu,
                usd_hr=admitted_pod.cost_per_hr,
                purpose=args.purpose,
            )
        pod = wait_ready(admitted_pod.id, timeout_s=args.ready_timeout)
        if pod.id != admitted_pod.id:
            raise RuntimeError(
                f"ready pod id changed: {pod.id!r} != {admitted_pod.id!r}"
            )
        _validate_pod_admission(
            pod,
            expected_gpu=offer["display_name"],
            max_usd_hr=args.max_usd_hr,
            min_vcpu=args.min_vcpu,
            min_mem_gb=args.min_mem_gb,
            name_prefix=args.name_prefix,
        )
        if pod.status != "RUNNING":
            raise RuntimeError(f"ready pod {pod.id} is not running: {pod.status}")
        ep = Endpoint.of(pod)
        log_file = RESULTS / "bootstrap" / f"{pod.id}.log"
        _install_deadman_first(
            ep,
            ttl_hours=args.ttl_hours,
            idle_min=args.idle_min,
            log_file=log_file,
        )
        if not bootstrap(
            ep,
            ttl_hours=args.ttl_hours,
            idle_min=args.idle_min,
            log_file=log_file,
        ):
            raise RuntimeError("bootstrap or deadman reinstall failed")
        # bootstrap replaces the first, verified watchdog. Reinstall and prove
        # the final daemon live before this admission can escape to proof work.
        _install_deadman_first(
            ep,
            ttl_hours=args.ttl_hours,
            idle_min=args.idle_min,
            log_file=log_file,
        )
        if not _resume_admission_is_current(
            admission, getattr(args, "recipe", None)
        ):
            raise RuntimeError("source-bound provider admission changed")
        _sync_pods_conf()
        return pod, ep
    except BaseException as error:
        if billing_possible:
            try:
                if args.failure_action == "terminate":
                    api.terminate_pod(admitted_pod.id)
                    ledger.append(
                        "terminate",
                        pod_id=admitted_pod.id,
                        gpu=admitted_pod.gpu,
                        note="admission-failure",
                    )
                    print("[gpufleet] failed admission termination confirmed")
                else:
                    terminal = api.stop_pod(admitted_pod.id)
                    ledger.append(
                        "stop",
                        pod_id=admitted_pod.id,
                        gpu=admitted_pod.gpu,
                        note="admission-failure",
                    )
                    print(f"[gpufleet] failed admission stop confirmed ({terminal})")
            except Exception as cleanup_error:
                raise RuntimeError(
                    f"URGENT: pod {admitted_pod.id} admission failed and "
                    f"{args.failure_action} was not confirmed: "
                    f"{cleanup_error}"
                ) from error
        raise


def _cleanup_failed_up(name: str, returned: api.PodInfo | None) -> None:
    """Terminate every exact-name candidate until absence has stayed stable."""
    started = time.monotonic()
    discovery_deadline = started + CREATE_RECONCILE_DISCOVERY_S
    deadline = started + CREATE_RECONCILE_TIMEOUT_S
    observed_create = False
    returned_id = (
        returned.id
        if returned is not None and POD_ID_RE.fullmatch(returned.id)
        else None
    )
    pending: dict[str, api.PodInfo] = {}
    clean_polls = 0
    last_error = None
    while True:
        now = time.monotonic()
        observed_this_poll = False
        try:
            matches = [pod for pod in api.list_pods() if pod.name == name]
            last_error = None
        except Exception as error:
            matches = []
            last_error = error

        independently_owned = {pod.id: pod for pod in matches}
        if returned_id is not None:
            try:
                exact = api.get_pod(returned_id)
                if exact is not None and exact.id != returned_id:
                    raise RuntimeError(
                        f"pod lookup returned {exact.id!r} for {returned_id!r}"
                    )
                if exact is not None and exact.name == name:
                    independently_owned[exact.id] = exact
                elif exact is not None:
                    raise RuntimeError(
                        f"returned pod identity mismatch: {exact.id!r} owns "
                        f"{exact.name!r}, not lease {name!r}"
                    )
            except Exception as error:
                last_error = error
        if independently_owned:
            observed_create = True
            observed_this_poll = True
            pending.update(independently_owned)

        attempted = bool(pending)
        for candidate_id, candidate in list(pending.items()):
            try:
                api.terminate_pod(candidate_id)
                ledger.append(
                    "terminate",
                    pod_id=candidate_id,
                    gpu=candidate.gpu,
                    note="up-failure",
                )
                del pending[candidate_id]
            except Exception as error:
                last_error = error

        clean = (
            last_error is None
            and not observed_this_poll
            and not attempted
            and not matches
            and not pending
        )
        eligible_clean = observed_create or now >= discovery_deadline
        clean_polls = clean_polls + 1 if clean and eligible_clean else 0
        if clean_polls >= 2:
            return
        if now >= deadline:
            detail = f": {last_error}" if last_error else ""
            raise RuntimeError(f"lease absence did not converge for {name!r}{detail}")
        time.sleep(min(CREATE_RECONCILE_POLL_S, max(0.0, deadline - now)))


def do_up(args) -> api.PodInfo | None:
    if args.cloud != "SECURE":
        print("REFUSED: bounded gpufleet provisioning requires Secure Cloud")
        return None
    policy = _apply_recipe_lease(args)
    _bind_explicit_ssh_key()
    if (
        not math.isfinite(args.ttl_hours)
        or args.ttl_hours <= 0
        or args.idle_min <= 0
        or not math.isfinite(args.ready_timeout)
        or args.ready_timeout <= 0
        or args.min_vcpu <= 0
        or args.min_mem_gb <= 0
        or not math.isfinite(args.max_usd_hr)
        or args.max_usd_hr <= 0
    ):
        raise ValueError("pod provisioning limits must be finite and positive")
    admission = _require_provider_admission(args, policy)
    if admission is None:
        return None
    gpu_type = _gpu_type(args.gpu)
    offer = api.secure_offer(gpu_type)
    price = offer["usd_hr"]
    if price > args.max_usd_hr:
        print(f"REFUSED: {gpu_type} at ${price:.2f}/hr exceeds ceiling "
              f"${args.max_usd_hr:.2f}/hr")
        return None
    name = _lease_name(args)
    if any(pod.name == name for pod in api.list_pods()):
        raise RuntimeError(f"refusing duplicate lease name already in account: {name}")
    print(f"[gpufleet] creating {gpu_type} (~${price:.2f}/hr, ttl {args.ttl_hours}h, "
          f"idle-stop {args.idle_min}min)")
    created_pod = None
    try:
        created_pod = api.create_pod(
            name=name,
            gpu_type_id=gpu_type,
            image=args.image,
            cloud="SECURE",
            disk_gb=args.disk_gb,
            volume_gb=args.volume_gb,
            volume_mount=VOLUME_MOUNT,
            min_vcpu=args.min_vcpu,
            min_mem_gb=args.min_mem_gb,
            network_volume_id=args.volume_id,
        )
        _validate_created_pod(created_pod, name, offer, args)
        _require_unique_account_pod(name, created_pod.id)
        ledger.append(
            "create",
            pod_id=created_pod.id,
            gpu=created_pod.gpu,
            usd_hr=created_pod.cost_per_hr,
            purpose=args.purpose,
        )
        print(f"[gpufleet] pod {created_pod.id} created; waiting for ssh ...")
        pod = wait_ready(created_pod.id, timeout_s=args.ready_timeout)
        if pod.id != created_pod.id:
            raise RuntimeError(
                f"ready pod id changed: {pod.id!r} != {created_pod.id!r}"
            )
        _validate_created_pod(pod, name, offer, args)
        if pod.status != "RUNNING":
            raise RuntimeError(f"ready pod {pod.id} is not running: {pod.status}")
        _require_unique_account_pod(name, pod.id)
        ep = Endpoint.of(pod)
        print(f"[gpufleet] ssh ready at {ep.host}:{ep.port}; bootstrapping ...")
        log_file = RESULTS / "bootstrap" / f"{pod.id}.log"
        _install_deadman_first(
            ep,
            ttl_hours=args.ttl_hours,
            idle_min=args.idle_min,
            log_file=log_file,
        )
        if not bootstrap(
            ep,
            ttl_hours=args.ttl_hours,
            idle_min=args.idle_min,
            log_file=log_file,
        ):
            raise RuntimeError("bootstrap failed")
        _install_deadman_first(
            ep,
            ttl_hours=args.ttl_hours,
            idle_min=args.idle_min,
            log_file=log_file,
        )
        for key, value in health_check(ep).items():
            print(f"  {key}: {value}")
        if (
            admission.get("scope") != "formal-pregate"
            and not _provider_admission_is_current(admission, args.recipe)
        ):
            raise RuntimeError("source-bound provider admission changed")
        _sync_pods_conf()
        print(f"[gpufleet] up: {pod.id}  ({ep.host}:{ep.port})")
        return pod
    except BaseException as error:
        try:
            _cleanup_failed_up(name, created_pod)
        except Exception as cleanup_error:
            raise RuntimeError(
                f"URGENT: failed provisioning cleanup for {name!r}: {cleanup_error}"
            ) from error
        raise


def cmd_up(args) -> int:
    return 0 if do_up(args) else 1


def _resolve_pod(pod_id: str) -> tuple[api.PodInfo, Endpoint]:
    pod = api.get_pod(pod_id)
    if not pod:
        raise SystemExit(f"no such pod: {pod_id}")
    return pod, Endpoint.of(pod)


def cmd_bootstrap(args) -> int:
    pod, ep = _resolve_pod(args.pod)
    ok = bootstrap(ep, ttl_hours=args.ttl_hours, idle_min=args.idle_min,
                   log_file=RESULTS / "bootstrap" / f"{pod.id}.log")
    print("bootstrap " + ("ok" if ok else "FAILED"))
    return 0 if ok else 1


def cmd_push(args) -> int:
    if not _require_pregate():
        return 1
    pod, _ep = _resolve_pod(args.pod)
    # build_and_push.sh drives itself from pods.conf (first line = builder unless
    # --builder): refresh the roster from the live API, then delegate.
    _sync_pods_conf()
    script = FLEET_DIR / "build_and_push.sh"
    return subprocess.run(
        ["bash", str(script), "--builder", pod.id], cwd=FLEET_DIR, check=False
    ).returncode


def cmd_run(args) -> int:
    if args.keep and (args.terminate or args.one_shot):
        raise ValueError("--keep conflicts with --terminate and --one-shot")
    if args.one_shot and args.failure_action != "terminate":
        raise ValueError("--one-shot requires --failure-action terminate")
    if args.auto:
        raise ValueError(
            "run --auto is retired; provision with `gpufleet up --recipe ...` "
            "and pass the admitted pod explicitly"
        )
    if not _require_pregate():
        return 1
    pod = None
    run_completed = False
    try:
        if args.pod:
            pod, ep = _prepare_existing_pod(args)
        else:
            print("need --pod ID")
            return 1

        if args.push:
            push_args = argparse.Namespace(pod=pod.id)
            if cmd_push(push_args) != 0:
                print("[gpufleet] push failed")
                return 1

        run = ManifestRun(Path(args.manifest), RESULTS, REPOS)
        summary = run.execute(
            ep, {"id": pod.id, "gpu": pod.gpu, "usd_hr": pod.cost_per_hr}
        )
        run_completed = True
        ledger.append(
            "run", pod_id=pod.id, gpu=pod.gpu, usd_hr=pod.cost_per_hr,
            purpose=args.purpose, run_id=summary["run_id"],
            note=("PASS" if summary["passed"] else "FAIL"),
        )
        print(
            f"[gpufleet] {'PASS' if summary['passed'] else 'FAIL'} — "
            f"results in {run.dir}"
        )
        return 0 if summary["passed"] else 1
    finally:
        # `--keep` applies only after the manifest returned. Every setup, push,
        # or execution exception still ends billing through a confirmed action.
        if pod is not None and args.keep and run_completed:
            print(f"[gpufleet] --keep: pod {pod.id} left RUNNING (billing!)")
        elif pod is not None and (args.terminate or args.one_shot):
            api.terminate_pod(pod.id)
            ledger.append("terminate", pod_id=pod.id, gpu=pod.gpu)
            print(f"[gpufleet] pod {pod.id} termination confirmed")
        elif pod is not None:
            terminal = api.stop_pod(pod.id)
            ledger.append("stop", pod_id=pod.id, gpu=pod.gpu)
            print(f"[gpufleet] pod {pod.id} stop confirmed ({terminal})")


def cmd_resume(args) -> int:
    pod, ep = _prepare_existing_pod(args)
    print(f"resume: {pod.id} ({pod.gpu}, guarded at {ep.host}:{ep.port})")
    return 0


def cmd_ssh(args) -> int:
    from .podctl import SSH_OPTS

    _, ep = _resolve_pod(args.pod)
    if args.remote_cmd:
        return ssh_run(ep, " ".join(args.remote_cmd))
    import os

    os.execvp("ssh", ["ssh", *SSH_OPTS, "-p", str(ep.port), f"root@{ep.host}"])


def cmd_check_manifest(args) -> int:
    """Validate a manifest offline: TOML parse, step shape, criterion ops."""
    try:
        run = ManifestRun(Path(args.manifest), RESULTS, REPOS)
    except Exception as e:
        print(f"INVALID: {e}")
        return 1
    steps = run.spec.get("step", [])
    ok = True
    if not steps:
        print("INVALID: no [[step]] entries")
        ok = False
    for s in steps:
        for key in ("name", "cmd"):
            if key not in s:
                print(f"INVALID: step missing {key!r}: {s}")
                ok = False
        for a in s.get("assert", []):
            if a.get("op", "eq") not in ("eq", "ne", "ge", "le", "exists", "contains"):
                print(f"INVALID: bad assert op in step {s.get('name')}: {a}")
                ok = False
    # The freshly-minted run dir is empty on a check — remove it.
    try:
        (run.dir / "summary.json").unlink(missing_ok=True)
        run.dir.rmdir()
    except OSError:
        pass
    if ok:
        print(f"OK: {run.name} ({len(steps)} steps)")
    return 0 if ok else 1


def _lifecycle(args, action: str) -> int:
    if args.all:
        targets = [p for p in api.list_pods()
                   if action != "stop" or p.status == "RUNNING"]
    elif args.pod:
        pod = api.get_pod(args.pod)
        targets = [pod] if pod else []
        # An explicit destructive action must prove the requested id terminal,
        # even when the first read says it is already absent.
        if pod is None:
            if action == "stop":
                terminal = api.stop_pod(args.pod)
                print(f"stop: {args.pod} ({terminal.lower()})")
            else:
                api.terminate_pod(args.pod)
                print(f"terminate: {args.pod} (absence confirmed)")
            return 0
    else:
        targets = []
    if not targets:
        print("nothing to do")
        return 0
    failures = []
    for p in targets:
        try:
            if action == "stop":
                terminal = api.stop_pod(p.id)
            else:
                api.terminate_pod(p.id)
            ledger.append(action, pod_id=p.id, gpu=p.gpu, usd_hr=p.cost_per_hr)
            if action == "stop":
                suffix = f", {terminal.lower()} confirmed"
            else:
                suffix = ", absence confirmed"
            print(f"{action}: {p.id} ({p.gpu}{suffix})")
        except Exception as error:
            failures.append(f"{p.id}: {error}")
    if failures:
        raise RuntimeError(f"{action} failures: " + "; ".join(failures))
    return 0


