    use crate::schedule_table::CAIRO_SCHEDULE;

    fn node(id: ComponentId) -> &'static ComponentNode {
        CAIRO_SCHEDULE
            .nodes
            .iter()
            .find(|node| node.id == id)
            .unwrap()
    }

    fn n_inputs(label: &str) -> usize {
        all_lane_recordings()
            .into_iter()
            .find(|(recorded, _)| *recorded == label)
            .unwrap()
            .1
            .n_inputs as usize
    }

    #[test]
    fn direct_w18_edge_and_host_enabler_have_exact_column_provenance() {
        let component = node("partial_ec_mul_window_bits_18");
        let columns =
            provenance_for_unmaterialized(component, n_inputs(component.id), 56, 64, |_| true)
                .unwrap();
        assert_eq!(columns.len(), 73);
        for (ordinal, source) in columns[..72].iter().enumerate() {
            assert!(matches!(
                source,
                RecordedInputColumnProvenance::DeviceEdge(DeviceEdgeColumn {
                    producer: "pedersen_aggregator_window_bits_18",
                    source_word,
                    words_per_instance: 72,
                    n_instances: 28,
                    ..
                }) if *source_word == 7 + ordinal as u32
            ));
        }
        assert!(matches!(
            columns[72],
            RecordedInputColumnProvenance::Host(_)
        ));
        assert!(columns
            .iter()
            .all(|source| !matches!(source, RecordedInputColumnProvenance::Unresolved(_))));
        let RecordedInputColumnProvenance::Host(enabler) = &columns[72] else {
            unreachable!()
        };
        assert_eq!(enabler.len(), 64);
        assert!(enabler[..56].iter().all(|&value| value == 1));
        assert!(enabler[56..].iter().all(|&value| value == 0));
        // This recording never reads iota, so the normalized recorder ABI
        // deliberately truncates the generated writer's trailing iota column.
    }

    #[test]
    fn poseidon_vec_consumers_use_ordered_multi_edge_gathers_without_host_columns() {
        for (component, expected) in [
            (
                "cube_252",
                vec![
                    ("poseidon_aggregator", 282, 2),
                    ("poseidon_3_partial_rounds_chain", 1, 3),
                    ("poseidon_full_round_chain", 0, 3),
                ],
            ),
            (
                "range_check_252_width_27",
                vec![
                    ("poseidon_aggregator", 262, 2),
                    ("poseidon_3_partial_rounds_chain", 61, 3),
                ],
            ),
        ] {
            let columns = provenance_for_unmaterialized(
                node(component),
                n_inputs(component),
                80,
                128,
                |_| true,
            )
            .unwrap();
            assert_eq!(columns.len(), 11, "{component}");
            for (word, source) in columns[..10].iter().enumerate() {
                let RecordedInputColumnProvenance::DeviceGather(DeviceGatherColumn::Data { edges }) =
                    source
                else {
                    panic!("{component} input {word} is not a device gather: {source:?}")
                };
                assert_eq!(edges.len(), expected.len(), "{component} input {word}");
                for (edge, &(producer, word_base, n_instances)) in edges.iter().zip(&expected) {
                    assert_eq!(
                        edge,
                        &DeviceEdgeColumn {
                            producer,
                            source_kind: DeviceEdgeSourceKind::SubcomponentWords,
                            source_word: word_base + word as u32,
                            words_per_instance: 10,
                            n_instances,
                        },
                        "{component} input {word} producer order",
                    );
                }
            }
            assert_eq!(
                columns[10],
                RecordedInputColumnProvenance::DeviceGather(DeviceGatherColumn::Enabler),
                "{component}",
            );
            // The generated row bodies never read iota, so recording
            // normalization removes slot 11 from both live programs.
            assert!(columns.iter().all(|source| !matches!(
                source,
                RecordedInputColumnProvenance::Host(_)
                    | RecordedInputColumnProvenance::Unresolved(_)
            )));
        }
    }

    #[test]
