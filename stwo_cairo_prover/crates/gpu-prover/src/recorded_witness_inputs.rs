//! Exact ProofPlan validation and per-column provenance for recorded witnesses.
//!
//! Canonical host construction stays beside the generated lane specs in
//! `stwo-cairo-prover`. Generator-fed columns that do not exist pre-witness are
//! never zero-filled: each is either a mechanically resolved producer edge or an
//! explicit unresolved column that keeps strict Graph-A admission fail-closed.

use std::sync::Arc;

use stwo_cairo_adapter::memory::Memory;
use stwo_cairo_prover::witness::cairo_claim_generator::CairoClaimGenerator;
use stwo_cairo_prover::witness::jit_prove_backend::{
    recorded_input_compaction_geometry, recorded_input_geometry, recorded_witness_input_attempt,
    ExecutionMemoryIdentity, RecordedInputBuildError, RecordedTableIdentity,
    RecordedWitnessInputSource, RecordedWitnessInputsError,
};
use stwo_cairo_prover::witness::proof_shape::{RowResolution, TracePartId};

use crate::plan::ProofPlan;
use crate::schedule::{ComponentId, ComponentNode, InputEdge, WitnessWriterKind};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DeviceEdgeSourceKind {
    SubcomponentWords,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DeviceEdgeColumn {
    pub producer: ComponentId,
    pub source_kind: DeviceEdgeSourceKind,
    /// Word within each producer instance; the gather repeats this ordinal over
    /// `n_instances` before flattening to the consumer column.
    pub source_word: u32,
    pub words_per_instance: u32,
    pub n_instances: u32,
}

/// One output column of the prepared ordered multi-producer gather. Data edges
/// are in the exact append order of the legacy `Mutex<Vec<_>>` consumer; the
/// mechanical tail is generated by the same capture-safe kernel.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum DeviceGatherColumn {
    Data { edges: Vec<DeviceEdgeColumn> },
    Enabler,
    Iota,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum UnresolvedColumnReason {
    NoProducerEdge,
    ProducerEdgesRequireCompaction {
        producer_count: usize,
    },
    ProducerEdgeGeometryMismatch {
        producer_words: usize,
        consumer_data_columns: usize,
    },
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct UnresolvedInputColumn {
    pub component: ComponentId,
    pub ordinal: usize,
    pub reason: UnresolvedColumnReason,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum RecordedInputColumnProvenance {
    Host(Vec<u32>),
    DeviceNative(DeviceNativeColumn),
    DeviceSeed(DeviceSeedColumn),
    DeviceEdge(DeviceEdgeColumn),
    DeviceGather(DeviceGatherColumn),
    DeviceCompact(DeviceCompactColumn),
    Unresolved(UnresolvedInputColumn),
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DeviceNativeColumn {
    pub producer: ComponentId,
    pub ordinal: usize,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum DeviceSeedColumn {
    Scalar { index: usize, value: u32 },
    Enabler,
    Iota,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DeviceCompactColumn {
    Tuple { word: usize },
    Enabler,
    Iota,
    Multiplicity,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PlannedRecordedWitnessInput {
    pub component: ComponentId,
    pub program: stwo_backend_cuda::jit_witness::isa::WitnessProgram,
    pub row_count: usize,
    pub n_real: usize,
    pub columns: Vec<RecordedInputColumnProvenance>,
    pub tables: RecordedTableIdentity,
    /// Why canonical host columns were unavailable. Device-edge resolution may
    /// still cover every column; unresolved columns always remain explicit.
    pub host_build_error: Option<RecordedInputBuildError>,
}

impl PlannedRecordedWitnessInput {
    pub fn unresolved_ordinals(&self) -> Vec<usize> {
        self.columns
            .iter()
            .enumerate()
            .filter_map(|(ordinal, source)| {
                matches!(source, RecordedInputColumnProvenance::Unresolved(_)).then_some(ordinal)
            })
            .collect()
    }
}

#[derive(Clone, Debug)]
pub struct PlannedRecordedWitnessInputs {
    pub execution_memory: Arc<Memory>,
    pub execution_memory_identity: ExecutionMemoryIdentity,
    pub lanes: Vec<PlannedRecordedWitnessInput>,
}

impl PlannedRecordedWitnessInputs {
    pub fn unresolved_columns(&self) -> Vec<(ComponentId, usize)> {
        self.lanes
            .iter()
            .flat_map(|lane| {
                lane.unresolved_ordinals()
                    .into_iter()
                    .map(|ordinal| (lane.component, ordinal))
            })
            .collect()
    }

    pub fn require_resolved(&self) -> Result<(), RecordedWitnessPlanError> {
        let unresolved = self.unresolved_columns();
        if unresolved.is_empty() {
            Ok(())
        } else {
            Err(RecordedWitnessPlanError::UnresolvedColumns(unresolved))
        }
    }
}

#[derive(Debug)]
pub enum RecordedWitnessPlanError {
    Inputs(RecordedWitnessInputsError),
    ShapeNotExact(ComponentId),
    InvalidTracePart(ComponentId),
    /// The witness dependency graph could not be topologically ordered
    /// (cyclic or dangling producer edges).
    UnorderableSchedule,
    RowGeometryMismatch {
        component: ComponentId,
        expected_real: usize,
        actual_real: usize,
        expected_padded: usize,
        actual_padded: usize,
    },
    UnsupportedLabels(Vec<ComponentId>),
    UnresolvedColumns(Vec<(ComponentId, usize)>),
    InputBuild {
        component: ComponentId,
        source: RecordedInputBuildError,
    },
    MissingInputGeometry(ComponentId),
    SizeOverflow(ComponentId),
}

impl core::fmt::Display for RecordedWitnessPlanError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "recorded witness ProofPlan rejected: {self:?}")
    }
}

impl std::error::Error for RecordedWitnessPlanError {}

impl From<RecordedWitnessInputsError> for RecordedWitnessPlanError {
    fn from(value: RecordedWitnessInputsError) -> Self {
        Self::Inputs(value)
    }
}

struct ExpectedLane {
    node: &'static ComponentNode,
    n_real: usize,
    row_count: usize,
}

/// Build one provenance-complete entry for every present RecordedAot component.
/// Host columns are exact recorder slots; direct producer columns are semantic
/// device-edge aliases; every remaining column is explicitly unresolved.
pub fn recorded_witness_inputs_for_plan(
    generator: &CairoClaimGenerator,
    proof_plan: &ProofPlan,
) -> Result<PlannedRecordedWitnessInputs, RecordedWitnessPlanError> {
    // Lanes must be planned in the same topological (producer-before-consumer)
    // order the arena witness workspace and the Graph A launcher use; the
    // resident session zips the two lists pairwise and fails closed on any
    // order drift. Plan order differs whenever a producer sorts after its
    // consumer (e.g. poseidon_aggregator after poseidon_3_partial_rounds_chain).
    let ordered = crate::arena_plan::topological_component_order(proof_plan)
        .map_err(|_| RecordedWitnessPlanError::UnorderableSchedule)?;
    let mut expected = Vec::new();
    for component in ordered {
        if component.node.facts.witness_writer.kind != WitnessWriterKind::RecordedAot
            || !component.runtime.is_present()
        {
            continue;
        }
        let RowResolution::Resolved(parts) = &component.runtime.rows else {
            return Err(RecordedWitnessPlanError::ShapeNotExact(component.node.id));
        };
        if parts.len() != 1 || parts[0].part != TracePartId::Main {
            return Err(RecordedWitnessPlanError::InvalidTracePart(
                component.node.id,
            ));
        }
        expected.push(ExpectedLane {
            node: component.node,
            n_real: usize::try_from(parts[0].n_real_rows)
                .map_err(|_| RecordedWitnessPlanError::SizeOverflow(component.node.id))?,
            row_count: usize::try_from(parts[0].padded_rows)
                .map_err(|_| RecordedWitnessPlanError::SizeOverflow(component.node.id))?,
        });
    }

    let labels = expected.iter().map(|lane| lane.node.id).collect::<Vec<_>>();
    let memory = generator
        .jit_memory
        .clone()
        .ok_or_else(|| RecordedWitnessInputsError::MissingExecutionMemory(labels.clone()))?;
    let execution_memory_identity = ExecutionMemoryIdentity::of(&memory);

    let mut attempts = Vec::with_capacity(expected.len());
    let mut unsupported = Vec::new();
    for lane in &expected {
        match recorded_witness_input_attempt(generator, lane.node.id)? {
            Some(attempt) => attempts.push(attempt),
            None => unsupported.push(lane.node.id),
        }
    }
    if !unsupported.is_empty() {
        return Err(RecordedWitnessPlanError::UnsupportedLabels(unsupported));
    }

    let mut lanes = Vec::with_capacity(expected.len());
    for (expected, attempt) in expected.into_iter().zip(attempts) {
        let program = attempt.program;
        let (columns, host_build_error) = match attempt.input_source {
            RecordedWitnessInputSource::Host(Ok(inputs)) => {
                let actual_padded = inputs.row_count();
                if inputs.n_real != expected.n_real || actual_padded != expected.row_count {
                    return Err(RecordedWitnessPlanError::RowGeometryMismatch {
                        component: expected.node.id,
                        expected_real: expected.n_real,
                        actual_real: inputs.n_real,
                        expected_padded: expected.row_count,
                        actual_padded,
                    });
                }
                (
                    inputs
                        .columns
                        .into_iter()
                        .map(RecordedInputColumnProvenance::Host)
                        .collect(),
                    None,
                )
            }
            RecordedWitnessInputSource::Host(Err(
                error @ RecordedInputBuildError::EmptyInputs(_),
            ))
            | RecordedWitnessInputSource::Host(Err(
                error @ RecordedInputBuildError::ScalarRemainder(_),
            ))
            | RecordedWitnessInputSource::Host(Err(
                error @ RecordedInputBuildError::DeviceSeedOnly(_),
            )) => (
                provenance_for_unmaterialized(
                    expected.node,
                    program.n_inputs as usize,
                    expected.n_real,
                    expected.row_count,
                    |producer| {
                        proof_plan.components.iter().any(|component| {
                            component.node.id == producer && component.runtime.is_present()
                        })
                    },
                )?,
                Some(error),
            ),
            RecordedWitnessInputSource::Host(Err(source)) => {
                return Err(RecordedWitnessPlanError::InputBuild {
                    component: expected.node.id,
                    source,
                });
            }
            RecordedWitnessInputSource::DeviceSeed(seed) => {
                if seed.n_real != expected.n_real || seed.row_count != expected.row_count {
                    return Err(RecordedWitnessPlanError::RowGeometryMismatch {
                        component: expected.node.id,
                        expected_real: expected.n_real,
                        actual_real: seed.n_real,
                        expected_padded: expected.row_count,
                        actual_padded: seed.row_count,
                    });
                }
                (
                    provenance_for_device_seed(
                        expected.node.id,
                        program.n_inputs as usize,
                        &seed.scalar_values,
                    )?,
                    None,
                )
            }
        };
        debug_assert_eq!(columns.len(), program.n_inputs as usize);
        lanes.push(PlannedRecordedWitnessInput {
            component: expected.node.id,
            program,
            row_count: expected.row_count,
            n_real: expected.n_real,
            columns,
            tables: RecordedTableIdentity {
                execution_memory: execution_memory_identity,
                host_pedersen_points_18: attempt.host_pedersen_points_18,
            },
            host_build_error,
        });
    }

    Ok(PlannedRecordedWitnessInputs {
        execution_memory: memory,
        execution_memory_identity,
        lanes,
    })
}

fn provenance_for_device_seed(
    component: ComponentId,
    n_inputs: usize,
    scalar_values: &[u32],
) -> Result<Vec<RecordedInputColumnProvenance>, RecordedWitnessPlanError> {
    let geometry = recorded_input_geometry(component)
        .ok_or(RecordedWitnessPlanError::MissingInputGeometry(component))?;
    let expected = scalar_values
        .len()
        .checked_add(usize::from(geometry.enabler_slot.is_some()))
        .and_then(|count| count.checked_add(usize::from(geometry.iota_slot.is_some())))
        .ok_or(RecordedWitnessPlanError::SizeOverflow(component))?;
    if n_inputs != expected
        || geometry.enabler_slot != Some(scalar_values.len())
        || geometry.iota_slot != Some(scalar_values.len() + 1)
    {
        return Err(RecordedWitnessPlanError::MissingInputGeometry(component));
    }
    let mut columns = scalar_values
        .iter()
        .copied()
        .enumerate()
        .map(|(index, value)| {
            RecordedInputColumnProvenance::DeviceSeed(DeviceSeedColumn::Scalar { index, value })
        })
        .collect::<Vec<_>>();
    columns.push(RecordedInputColumnProvenance::DeviceSeed(
        DeviceSeedColumn::Enabler,
    ));
    columns.push(RecordedInputColumnProvenance::DeviceSeed(
        DeviceSeedColumn::Iota,
    ));
    Ok(columns)
}

fn provenance_for_unmaterialized(
    node: &'static ComponentNode,
    n_inputs: usize,
    n_real: usize,
    row_count: usize,
    producer_is_active: impl Fn(ComponentId) -> bool,
) -> Result<Vec<RecordedInputColumnProvenance>, RecordedWitnessPlanError> {
    let geometry = recorded_input_geometry(node.id)
        .ok_or(RecordedWitnessPlanError::MissingInputGeometry(node.id))?;
    if node.id == "partial_ec_mul_generic" && producer_is_active("ec_op_builtin") {
        let ec_rows = n_real
            .checked_div(252)
            .filter(|_| n_real % 252 == 0)
            .ok_or(RecordedWitnessPlanError::MissingInputGeometry(node.id))?;
        // The recording treats iota as computed in-kernel (the lane convention),
        // so its inputs are the 125 data columns plus the enabler at slot 125.
        // The native ec_op writer still materializes the one-past-end iota
        // column into its own arena slot; the witness launch never binds it.
        if n_inputs != 126
            || geometry.enabler_slot != Some(125)
            || geometry.iota_slot != Some(126)
            || row_count != ec_rows.saturating_mul(256)
        {
            return Err(RecordedWitnessPlanError::MissingInputGeometry(node.id));
        }
        return Ok((0..n_inputs)
            .map(|ordinal| {
                RecordedInputColumnProvenance::DeviceNative(DeviceNativeColumn {
                    producer: "ec_op_builtin",
                    ordinal,
                })
            })
            .collect());
    }
    let producer_edges = node
        .inputs
        .iter()
        .filter_map(|edge| match edge {
            InputEdge::Producer {
                of,
                word_base,
                words_per_instance,
                n_instances,
            } if producer_is_active(*of) => {
                Some((*of, *word_base, *words_per_instance, *n_instances))
            }
            InputEdge::ExecTables | InputEdge::DeviceTable(_) => None,
            InputEdge::Producer { .. } => None,
        })
        .collect::<Vec<_>>();
    if let Some(compaction) = recorded_input_compaction_geometry(node.id) {
        let enabler_slot = geometry.enabler_slot;
        let iota_slot = geometry.iota_slot;
        if producer_edges.is_empty()
            || compaction.tuple_words == 0
            || compaction.tuple_words > n_inputs
            || compaction.multiplicity_slot >= n_inputs
            || enabler_slot.is_none_or(|slot| slot >= n_inputs)
            || iota_slot.is_none_or(|slot| slot >= n_inputs)
            || producer_edges
                .iter()
                .any(|edge| edge.2 as usize != compaction.tuple_words)
        {
            return Err(RecordedWitnessPlanError::MissingInputGeometry(node.id));
        }
        let mut columns = vec![None; n_inputs];
        for (word, destination) in columns[..compaction.tuple_words].iter_mut().enumerate() {
            *destination = Some(RecordedInputColumnProvenance::DeviceCompact(
                DeviceCompactColumn::Tuple { word },
            ));
        }
        columns[enabler_slot.unwrap()] = Some(RecordedInputColumnProvenance::DeviceCompact(
            DeviceCompactColumn::Enabler,
        ));
        columns[iota_slot.unwrap()] = Some(RecordedInputColumnProvenance::DeviceCompact(
            DeviceCompactColumn::Iota,
        ));
        columns[compaction.multiplicity_slot] = Some(RecordedInputColumnProvenance::DeviceCompact(
            DeviceCompactColumn::Multiplicity,
        ));
        return columns
            .into_iter()
            .collect::<Option<Vec<_>>>()
            .ok_or(RecordedWitnessPlanError::MissingInputGeometry(node.id));
    }
    let data_ordinals = (0..n_inputs)
        .filter(|ordinal| {
            Some(*ordinal) != geometry.enabler_slot && Some(*ordinal) != geometry.iota_slot
        })
        .collect::<Vec<_>>();
    let unresolved_reason = match producer_edges.as_slice() {
        [] => UnresolvedColumnReason::NoProducerEdge,
        [_] => UnresolvedColumnReason::ProducerEdgeGeometryMismatch {
            producer_words: producer_edges[0].2 as usize,
            consumer_data_columns: data_ordinals.len(),
        },
        edges => UnresolvedColumnReason::ProducerEdgesRequireCompaction {
            producer_count: edges.len(),
        },
    };
    let mut columns = (0..n_inputs)
        .map(|ordinal| {
            RecordedInputColumnProvenance::Unresolved(UnresolvedInputColumn {
                component: node.id,
                ordinal,
                reason: unresolved_reason.clone(),
            })
        })
        .collect::<Vec<_>>();

    let multi_gather = producer_edges.len() > 1
        && producer_edges
            .iter()
            .all(|edge| edge.2 as usize == data_ordinals.len());
    if let [(producer, word_base, words_per_instance, n_instances)] = producer_edges.as_slice() {
        if *words_per_instance as usize == data_ordinals.len() {
            for (source_offset, &ordinal) in data_ordinals.iter().enumerate() {
                columns[ordinal] = RecordedInputColumnProvenance::DeviceEdge(DeviceEdgeColumn {
                    producer: *producer,
                    source_kind: DeviceEdgeSourceKind::SubcomponentWords,
                    source_word: *word_base + source_offset as u32,
                    words_per_instance: *words_per_instance,
                    n_instances: *n_instances,
                });
            }
        }
    } else if multi_gather {
        for (source_offset, &ordinal) in data_ordinals.iter().enumerate() {
            columns[ordinal] =
                RecordedInputColumnProvenance::DeviceGather(DeviceGatherColumn::Data {
                    edges: producer_edges
                        .iter()
                        .map(|(producer, word_base, words_per_instance, n_instances)| {
                            DeviceEdgeColumn {
                                producer: *producer,
                                source_kind: DeviceEdgeSourceKind::SubcomponentWords,
                                source_word: *word_base + source_offset as u32,
                                words_per_instance: *words_per_instance,
                                n_instances: *n_instances,
                            }
                        })
                        .collect(),
                });
        }
    }
    if let Some(ordinal) = geometry.enabler_slot.filter(|&ordinal| ordinal < n_inputs) {
        columns[ordinal] = if multi_gather {
            RecordedInputColumnProvenance::DeviceGather(DeviceGatherColumn::Enabler)
        } else {
            RecordedInputColumnProvenance::Host(
                (0..row_count).map(|row| u32::from(row < n_real)).collect(),
            )
        };
    }
    if let Some(ordinal) = geometry.iota_slot.filter(|&ordinal| ordinal < n_inputs) {
        columns[ordinal] = if multi_gather {
            RecordedInputColumnProvenance::DeviceGather(DeviceGatherColumn::Iota)
        } else {
            RecordedInputColumnProvenance::Host(
                (0..row_count)
                    .map(|row| u32::try_from(row).expect("Cairo trace row exceeds u32"))
                    .collect(),
            )
        };
    }
    Ok(columns)
}

