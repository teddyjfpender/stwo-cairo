    #[test]
    fn poseidon_device_only_chain_resolves_to_arena_input_materializers() {
        let memory = Arc::new(Memory {
            config: MemoryConfig::default(),
            address_to_id: vec![EncodedMemoryValueId(0)],
            f252_values: vec![[0; 8]],
            small_values: vec![0],
        });
        let generator = CairoClaimGenerator {
            jit_memory: Some(memory),
            poseidon_builtin: Some(poseidon_builtin::ClaimGenerator::new(4, 17)),
            poseidon_aggregator: Some(poseidon_aggregator::ClaimGenerator::new()),
            poseidon_full_round_chain: Some(poseidon_full_round_chain::ClaimGenerator::new()),
            poseidon_3_partial_rounds_chain: Some(
                poseidon_3_partial_rounds_chain::ClaimGenerator::new(),
            ),
            ..CairoClaimGenerator::default()
        };
        let capacity = ProofPlan::from_schedule(
            &CAIRO_SCHEDULE,
            &CAIRO_RELATION_GRAPH,
            &generator.proof_shape(None).unwrap(),
        )
        .unwrap();
        // The strict resolution fails closed on the compacted aggregator's
        // capacity bound; this lane-provenance test substitutes the capacity
        // geometry explicitly (see resolve_compacted_capacity_for_test).
        let exact = crate::plan::resolve_compacted_capacity_for_test(
            &capacity,
            &CAIRO_SCHEDULE,
            &CAIRO_RELATION_GRAPH,
        )
        .strict_resident_exact(&CAIRO_SCHEDULE, &CAIRO_RELATION_GRAPH)
        .unwrap();
        let planned = recorded_witness_inputs_for_plan(&generator, &exact).unwrap();
        planned.require_resolved().unwrap();
        assert_eq!(planned.lanes.len(), 4);

        let lane = |component| {
            planned
                .lanes
                .iter()
                .find(|lane| lane.component == component)
                .unwrap()
        };
        assert_eq!(
            lane("poseidon_builtin").columns,
            [
                RecordedInputColumnProvenance::DeviceSeed(DeviceSeedColumn::Scalar {
                    index: 0,
                    value: 17,
                }),
                RecordedInputColumnProvenance::DeviceSeed(DeviceSeedColumn::Enabler),
                RecordedInputColumnProvenance::DeviceSeed(DeviceSeedColumn::Iota),
            ]
        );
        assert!(lane("poseidon_aggregator")
            .columns
            .iter()
            .all(|source| matches!(source, RecordedInputColumnProvenance::DeviceCompact(_))));

        for (component, word_base, input_width, n_instances) in [
            ("poseidon_full_round_chain", 6, 32, 8),
            ("poseidon_3_partial_rounds_chain", 342, 42, 27),
        ] {
            let lane = lane(component);
            // These generated chain writers read the producer words and the
            // enabler, but not iota; input normalization removes that trailing
            // unused column from the recorded ABI.
            assert_eq!(lane.columns.len(), input_width + 1);
            for (ordinal, source) in lane.columns[..input_width].iter().enumerate() {
                assert!(matches!(
                    source,
                    RecordedInputColumnProvenance::DeviceEdge(DeviceEdgeColumn {
                        producer: "poseidon_aggregator",
                        source_word,
                        words_per_instance,
                        n_instances: actual_instances,
                        ..
                    }) if *source_word == word_base + ordinal as u32
                        && *words_per_instance == input_width as u32
                        && *actual_instances == n_instances
                ));
            }
            assert!(matches!(
                lane.columns[input_width],
                RecordedInputColumnProvenance::Host(_)
            ));
        }
    }

    #[test]
    fn exact_host_lane_covers_program_rows_and_retains_memory_identity() {
        let memory = Arc::new(Memory {
            config: MemoryConfig::default(),
            address_to_id: vec![EncodedMemoryValueId(0)],
            f252_values: vec![[0; 8]],
            small_values: vec![0],
        });
        let mut generator = CairoClaimGenerator {
            jit_memory: Some(memory.clone()),
            ..CairoClaimGenerator::default()
        };
        generator.add_opcode = Some(
            stwo_cairo_prover::witness::components::add_opcode::ClaimGenerator::new(vec![
                CasmState {
                    pc: M31::from_u32_unchecked(1),
                    ap: M31::from_u32_unchecked(2),
                    fp: M31::from_u32_unchecked(3),
                },
                CasmState {
                    pc: M31::from_u32_unchecked(4),
                    ap: M31::from_u32_unchecked(5),
                    fp: M31::from_u32_unchecked(6),
                },
                CasmState {
                    pc: M31::from_u32_unchecked(7),
                    ap: M31::from_u32_unchecked(8),
                    fp: M31::from_u32_unchecked(9),
                },
            ]),
        );
        let shape = generator.proof_shape(None).unwrap();
        let plan =
            ProofPlan::from_schedule(&CAIRO_SCHEDULE, &CAIRO_RELATION_GRAPH, &shape).unwrap();
        let planned = recorded_witness_inputs_for_plan(&generator, &plan).unwrap();

        assert!(Arc::ptr_eq(&planned.execution_memory, &memory));
        assert_eq!(
            planned.execution_memory_identity,
            ExecutionMemoryIdentity::of(&memory)
        );
        assert_eq!(planned.lanes.len(), 1);
        let lane = &planned.lanes[0];
        assert_eq!(lane.component, "add_opcode");
        assert_eq!(lane.program.label, lane.component);
        assert_eq!(lane.n_real, 3);
        assert_eq!(lane.row_count, 16);
        assert_eq!(lane.columns.len(), lane.program.n_inputs as usize);
        assert!(lane
            .columns
            .iter()
            .all(|source| matches!(source, RecordedInputColumnProvenance::Host(column) if column.len() == lane.row_count)));
        assert!(planned.unresolved_columns().is_empty());
        planned.require_resolved().unwrap();
        let RecordedInputColumnProvenance::Host(pc) = &lane.columns[0] else {
            unreachable!()
        };
        assert_eq!(&pc[..3], &[1, 4, 7]);
    }
